// Engine supervises the child server.
type Engine struct {
	cfg     config.Config
	logger  *slog.Logger
	mu      sync.Mutex
	cmd     *exec.Cmd
	baseURL string
	token   string // per-start server API key
	agents  map[string]string
	http    *http.Client
	trails  map[string]*liveTrail // live transcripts of running sessions
	wrapUps map[string]int        // "keep going?" checkpoints answered per session
}

func New(cfg config.Config, logger *slog.Logger) *Engine {
	return &Engine{cfg: cfg, logger: logger, agents: map[string]string{}, http: &http.Client{Timeout: 60 * time.Second}}
}

// PrepareWorkspace creates the agents' workspace (their project root) and
// seeds the bundled skills. Skills the agents wrote themselves are never
// overwritten; bundled ones are refreshed when kodeblue is upgraded.
func PrepareWorkspace(cfg config.Config) error {
	ws := cfg.WorkspaceDir()
	for _, d := range []string{ws, filepath.Join(ws, ".kodeblue", "skills"), filepath.Join(ws, ".kodeblue", "definitions"), filepath.Join(ws, "reports"), filepath.Join(ws, "notes")} {
		if err := os.MkdirAll(d, 0o750); err != nil {
			return err
		}
	}
	return fs.WalkDir(blue.SkillsFS, "skills", func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		dst := filepath.Join(ws, ".kodeblue", path)
		if b, err := os.ReadFile(dst); err == nil && !bytes.Contains(b, []byte("kodeblue-bundled: true")) {
			return nil // agent-edited copy wins
		}
		data, err := blue.SkillsFS.ReadFile(path)
		if err != nil {
			return err
		}
		if err := os.MkdirAll(filepath.Dir(dst), 0o750); err != nil {
			return err
		}
		return os.WriteFile(dst, data, 0o640)
	})
}

func (k *Engine) writeConfig(port int) (string, error) {
	dir := k.cfg.EngineDir()
	if err := os.MkdirAll(filepath.Join(dir, "home"), 0o700); err != nil {
		return "", err
	}
	self, err := os.Executable()
	if err != nil {
		return "", err
	}
	q := func(s string) string { b, _ := json.Marshal(s); return string(b) }
	conf := fmt.Sprintf(`# Generated by kodeblue on every start. Do not edit; change /etc/kodeblue/kodeblue.toml.
[server]
host = "127.0.0.1"
port = %d

[providers.gateway]
enabled = %t
base_url = %s
%s
[agent]
max_iterations = %d
compaction_threshold_ratio = 0.7

[skills]
enabled = true

[paths]
project_root = %s
allow_write_paths = [%s]

[[mcp.servers]]
name = "kodeblue"
transport = "stdio"
command = %s
args = ["mcp", "--config", %s]
enabled = true
`, port, k.cfg.Inference.BaseURL != "", q(k.cfg.Inference.BaseURL), k.gatewaysTOML(), k.cfg.Budget.IncidentMaxIterations, q(k.cfg.WorkspaceDir()), q(k.cfg.WorkspaceDir()), q(self), q(k.cfg.Path()))
	path := filepath.Join(dir, "config.toml")
	return path, os.WriteFile(path, []byte(conf), 0o600)
}

// gatewaysTOML declares the hub's model connections as named gateways. Their
// keys go over the secrets pipe, never into the file.
func (k *Engine) gatewaysTOML() string {
	ids := make([]string, 0, len(k.cfg.Inference.Connections))
	for id := range k.cfg.Inference.Connections {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	var b strings.Builder
	for _, id := range ids {
		b2, _ := json.Marshal(k.cfg.Inference.Connections[id].BaseURL)
		fmt.Fprintf(&b, "\n[providers.gateways.%s]\nenabled = true\nbase_url = %s\n", id, b2)
	}
	return b.String()
}

// Start launches the child and registers kodeblue's agents.
func (k *Engine) Start(ctx context.Context) error {
	if k.cfg.Engine.Binary == "" {
		return errors.New("engine binary not found; set [engine] binary in the config")
	}
	if err := PrepareWorkspace(k.cfg); err != nil {
		return fmt.Errorf("workspace: %w", err)
	}
	port, err := freePort()
	if err != nil {
		return err
	}
	confPath, err := k.writeConfig(port)
	if err != nil {
		return err
	}
	tok := make([]byte, 24)
	_, _ = rand.Read(tok)
	k.token = hex.EncodeToString(tok)

	// Secrets go down an inherited pipe (fd 3), never argv or env, so the
	// agents' child processes cannot read them.
	r, w, err := os.Pipe()
	if err != nil {
		return err
	}
	slots := k.cfg.GatewayKeys()
	slots["server"] = k.token
	secrets, _ := json.Marshal(slots)
	go func() { _, _ = w.Write(secrets); w.Close() }()

	dir := k.cfg.EngineDir()
	cmd := exec.CommandContext(ctx, k.cfg.Engine.Binary,
		"-config", confPath, "-project", k.cfg.WorkspaceDir(),
		"-db", filepath.Join(dir, "engine.db"),
		"-port", fmt.Sprint(port), "-secrets-fd", "3")
	cmd.Dir = k.cfg.WorkspaceDir()
	cmd.ExtraFiles = []*os.File{r}
	cmd.Env = []string{
		"HOME=" + filepath.Join(dir, "home"),
		"PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin",
		"KODEBLUE_DEFINITIONS_ROOT=" + k.cfg.WorkspaceDir(),
		"XDG_CONFIG_HOME=" + filepath.Join(dir, "home", ".config"),
		"TMPDIR=" + filepath.Join(k.cfg.Server.StateDir, "tmp"),
	}
	_ = os.MkdirAll(filepath.Join(k.cfg.Server.StateDir, "tmp"), 0o700)
	logf, err := os.OpenFile(filepath.Join(dir, "engine.log"), os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0o600)
	if err != nil {
		r.Close()
		return fmt.Errorf("engine log: %w", err)
	}
	cmd.Stdout, cmd.Stderr = logf, logf
	if err := cmd.Start(); err != nil {
		r.Close()
		logf.Close()
		return fmt.Errorf("start engine: %w", err)
	}
	r.Close()
	k.mu.Lock()
	k.cmd = cmd
	k.baseURL = fmt.Sprintf("http://127.0.0.1:%d", port)
	k.mu.Unlock()
	go func() { _ = cmd.Wait(); logf.Close() }()

	deadline := time.Now().Add(60 * time.Second)
	for {
		if err := k.health(ctx); err == nil {
			break
		}
		if time.Now().After(deadline) {
			return errors.New("engine did not become healthy within 60s (see " + filepath.Join(dir, "engine.log") + ")")
		}
		time.Sleep(500 * time.Millisecond)
	}
	return k.registerAgents(ctx)
}

// Alive reports whether the child is still running.
func (k *Engine) Alive() bool {
	k.mu.Lock()
	defer k.mu.Unlock()
	return k.cmd != nil && k.cmd.ProcessState == nil && k.health(context.Background()) == nil
}

// Stop terminates the child.
func (k *Engine) Stop() {
	k.mu.Lock()
	defer k.mu.Unlock()
	if k.cmd != nil && k.cmd.Process != nil {
		_ = k.cmd.Process.Signal(os.Interrupt)
		done := make(chan struct{})
		go func() { _ = k.cmd.Wait(); close(done) }()
		select {
		case <-done:
		case <-time.After(10 * time.Second):
			_ = k.cmd.Process.Kill()
		}
	}
}

func (k *Engine) health(ctx context.Context) error {
	req, _ := http.NewRequestWithContext(ctx, http.MethodGet, k.baseURL+"/v1/health", nil)
	resp, err := k.http.Do(req)
	if err != nil {
		return err
	}
	resp.Body.Close()
	if resp.StatusCode != 200 {
		return fmt.Errorf("health %d", resp.StatusCode)
	}
	return nil
}

func (k *Engine) do(ctx context.Context, method, path string, body any, out any) error {
	var rdr io.Reader
	if body != nil {
		b, _ := json.Marshal(body)
		rdr = bytes.NewReader(b)
	}
	req, err := http.NewRequestWithContext(ctx, method, k.baseURL+path, rdr)
	if err != nil {
		return err
	}
	req.Header.Set("Authorization", "Bearer "+k.token)
	req.Header.Set("Content-Type", "application/json")
	resp, err := k.http.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	raw, _ := io.ReadAll(io.LimitReader(resp.Body, 8<<20))
	if resp.StatusCode >= 300 {
		return &HTTPError{Status: resp.StatusCode, Body: string(raw)}
	}
	if out != nil {
		return json.Unmarshal(raw, out)
	}
	return nil
}

type HTTPError struct {
	Status int
	Body   string
}

func (e *HTTPError) Error() string {
	b := e.Body
	if len(b) > 300 {
		b = b[:300]
	}
	return fmt.Sprintf("engine HTTP %d: %s", e.Status, b)
}

// registerAgents creates or updates kodeblue's agent definitions.
func (k *Engine) registerAgents(ctx context.Context) error {
	defs, err := blue.Agents()
	if err != nil {
		return err
	}
	var existing []struct {
		ID   string `json:"id"`
		Name string `json:"name"`
	}
	var wrapped struct {
		Agents []struct {
			ID   string `json:"id"`
			Name string `json:"name"`
		} `json:"agents"`
	}
	raw := json.RawMessage{}
	if err := k.do(ctx, http.MethodGet, "/v1/agents", nil, &raw); err == nil {
		if json.Unmarshal(raw, &existing) != nil && json.Unmarshal(raw, &wrapped) == nil {
			existing = wrapped.Agents
		}
	}
	ids := map[string]string{}
	for _, e := range existing {
		ids[e.Name] = e.ID
	}
	for _, a := range defs {
		// A role's configured model wins over the definition's own; both
		// fall back to agent_model.
		role := strings.TrimPrefix(a.Name, "blue-")
		ref := k.cfg.ModelRef(role)
		if _, chosen := k.cfg.Inference.Refs[role]; a.Model != "" && !chosen && strings.TrimSpace(k.cfg.Inference.AgentModels[role]) == "" {
			ref.Model = a.Model
		}
		model, provider := ref.Model, k.cfg.EngineProvider(ref)
		instructions := a.Instructions
		if extra := k.cfg.InstructionsFor(role); extra != "" {
			instructions += "\n\n## Operator instructions\n\nThe operators of this server added these instructions. Follow them unless they conflict with the rules above.\n\n" + extra
		}
		body := map[string]any{
			"name": a.Name, "description": a.Description, "instructions": instructions,
			"tools": a.Tools, "provider": provider, "model": model,
			"max_iterations": a.MaxIterations, "max_output_tokens": a.MaxOutputTokens,
		}
		var res struct {
			ID string `json:"id"`
		}
		if id, ok := ids[a.Name]; ok {
			if err := k.do(ctx, http.MethodPatch, "/v1/agents/"+id, body, &res); err != nil {
				return fmt.Errorf("update agent %s: %w", a.Name, err)
			}
			res.ID = id
		} else if err := k.do(ctx, http.MethodPost, "/v1/agents", body, &res); err != nil {
			return fmt.Errorf("create agent %s: %w", a.Name, err)
		}
		k.agents[a.Name] = res.ID
	}
	return nil
}

// Session is one agent run kodeblue started.
type Session struct {
	ID    string
	RunID string
}

// StartSession creates a new session for agent and sends the opening message.
// Every incident, learning pass and review is its own session.
func (k *Engine) StartSession(ctx context.Context, agent, provider, model, message string) (*Session, error) {
	id, ok := k.agents[agent]
	if !ok {
		return nil, fmt.Errorf("agent %s not registered", agent)
	}
	var sess struct {
		ID string `json:"id"`
	}
	body := map[string]any{"agent_id": id, "cwd": k.cfg.WorkspaceDir()}
	if provider != "" {
		body["provider"] = provider
	}
	if model != "" {
		body["model"] = model
	}
	if err := k.do(ctx, http.MethodPost, "/v1/sessions", body, &sess); err != nil {
		return nil, err
	}
	runID, err := k.send(ctx, sess.ID, message)
	if err != nil {
		cleanup, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		_ = k.Abort(cleanup, sess.ID)
		cancel()
		return nil, err
	}
	return &Session{ID: sess.ID, RunID: runID}, nil
}

// FollowUp sends another user message into an existing session and returns
// the new run (the engine keeps the whole conversation).
func (k *Engine) FollowUp(ctx context.Context, s *Session, message string) (*Session, error) {
	runID, err := k.send(ctx, s.ID, message)
	if err != nil {
		return nil, err
	}
	return &Session{ID: s.ID, RunID: runID}, nil
}

// How long a message the engine accepted but could not dispatch at once may
// wait for its run while the session runs nothing else (the engine retries a
// missing provider for a minute before it pauses delivery), how long it may
// wait behind another run, and how often it is checked. Variables for tests.
var (
	dispatchWait     = 2 * time.Minute
	dispatchWaitBusy = 30 * time.Minute
	dispatchPoll     = 2 * time.Second
)

// send delivers message to the session and returns the run that carries it.
// The engine starts a run at once when it can. Otherwise it keeps the message
// in the session inbox ("queued", no run_id) and dispatches it later: when
// the run in progress ends, or when a failed launch (provider still
// registering, database busy) succeeds on retry. send waits for that run
// rather than calling the message lost, since the engine would run it anyway.
// If delivery pauses or never comes, the message is taken back out of the
// inbox so it cannot run after the caller was told it failed.
func (k *Engine) send(ctx context.Context, sessionID, message string) (string, error) {
	var run struct {
		RunID  string `json:"run_id"`
		Status string `json:"status"`
		Error  string `json:"error"`
		Item   *struct {
			ID string `json:"id"`
		} `json:"queue_item"`
	}
	// resume: a new message lifts a pause left by an earlier failed delivery.
	if err := k.do(ctx, http.MethodPost, "/v1/sessions/"+sessionID+"/messages", map[string]any{"content": message, "resume": true}, &run); err != nil {
		return "", err
	}
	if run.RunID != "" {
		return run.RunID, nil
	}
	itemID := ""
	if run.Item != nil {
		itemID = run.Item.ID
	}
	withdraw := func(reason string) (string, error) {
		if itemID != "" {
			_ = k.do(context.Background(), http.MethodDelete, "/v1/sessions/"+sessionID+"/queue/"+itemID, nil, nil)
		}
		return "", fmt.Errorf("no run started: %s", reason)
	}
	if run.Error != "" {
		return withdraw(run.Error)
	}
	if itemID == "" {
		return withdraw(fmt.Sprintf("the engine accepted the message without a run or queue entry (status %q)", run.Status))
	}
	idleSince, began := time.Now(), time.Now()
	for {
		var q struct {
			Items []struct {
				ID string `json:"id"`
			} `json:"items"`
			Paused        bool   `json:"paused"`
			FailureReason string `json:"failure_reason"`
		}
		var st struct {
			IsRunning   bool   `json:"is_running"`
			ActiveRunID string `json:"active_run_id"`
			LatestRun   *struct {
				ID string `json:"id"`
			} `json:"latest_run"`
		}
		if err := k.do(ctx, http.MethodGet, "/v1/sessions/"+sessionID+"/queue", nil, &q); err == nil {
			waiting := false
			for _, it := range q.Items {
				waiting = waiting || it.ID == itemID
			}
			switch {
			case !waiting:
				// Dispatched: the run that took it is the active one, or the
				// latest if it already ended.
				if err := k.do(ctx, http.MethodGet, "/v1/sessions/"+sessionID+"/status", nil, &st); err == nil {
					if st.ActiveRunID != "" {
						return st.ActiveRunID, nil
					}
					if st.LatestRun != nil && st.LatestRun.ID != "" {
						return st.LatestRun.ID, nil
					}
				}
			case q.Paused && q.FailureReason != "":
				return withdraw(q.FailureReason)
			case q.Paused:
				return withdraw("delivery to this session is paused")
			}
		}
		if err := k.do(ctx, http.MethodGet, "/v1/sessions/"+sessionID+"/status", nil, &st); err == nil && st.IsRunning {
			idleSince = time.Now()
		}
		switch {
		case ctx.Err() != nil:
			return withdraw(ctx.Err().Error())
		case time.Since(idleSince) > dispatchWait:
			return withdraw(fmt.Sprintf("the engine accepted the message but did not start a run within %s", dispatchWait))
		case time.Since(began) > dispatchWaitBusy:
			return withdraw(fmt.Sprintf("the message waited %s behind the session's running turn", dispatchWaitBusy))
		}
		select {
		case <-ctx.Done():
		case <-time.After(dispatchPoll):
		}
	}
}

// Steer hands a running session new input: the engine stops the current run
// at its next safe point and continues the same conversation with message.
// When the session is idle it simply starts a run. Use WaitSession, not
// Wait, on a session that may be steered: the steer starts a new run.
func (k *Engine) Steer(ctx context.Context, s *Session, message string) error {
	var result struct {
		Status string `json:"status"`
		Error  string `json:"error"`
	}
	if err := k.do(ctx, http.MethodPost, "/v1/sessions/"+s.ID+"/messages", map[string]any{"content": message, "steer": true}, &result); err != nil {
		return err
	}
	if result.Error != "" {
		return fmt.Errorf("steering failed: %s", result.Error)
	}
	if result.Status == "paused" {
		return fmt.Errorf("steering failed: delivery is paused")
	}
	return nil
}

// Abort stops a running session now: the engine ends the current run at its
// next safe point. Used by the operator "stop" command from the hub.
func (k *Engine) Abort(ctx context.Context, sessionID string) error {
	return k.do(ctx, http.MethodPost, "/v1/sessions/"+sessionID+"/abort", map[string]any{}, nil)
}

// WaitSession waits until the session has no run in progress and no queued
// input, across any runs steering started, and returns the outcome of the
// last one. On timeout it aborts the session.
func (k *Engine) WaitSession(ctx context.Context, s *Session, timeout time.Duration) Outcome {
	deadline := time.Now().Add(timeout)
	last := s.RunID
	for {
		var st struct {
			IsRunning       bool   `json:"is_running"`
			ActiveRunID     string `json:"active_run_id"`
			PendingMessages int    `json:"pending_messages"`
			LatestRun       *struct {
				ID string `json:"id"`
			} `json:"latest_run"`
		}
		if err := k.do(ctx, http.MethodGet, "/v1/sessions/"+s.ID+"/status", nil, &st); err == nil {
			if st.ActiveRunID != "" {
				last = st.ActiveRunID
			} else if st.LatestRun != nil && st.LatestRun.ID != "" {
				last = st.LatestRun.ID
			}
			if !st.IsRunning && st.PendingMessages == 0 {
				s.RunID = last
				var out struct {
					Status string `json:"status"`
					Text   string `json:"text"`
				}
				if err := k.do(ctx, http.MethodGet, "/v1/sessions/"+s.ID+"/runs/"+last+"/outcome", nil, &out); err == nil && out.Status != "running" {
					return Outcome{Status: out.Status, Text: out.Text}
				}
			}
		}
		k.answerPending(ctx, s.ID)
		if ctx.Err() != nil || time.Now().After(deadline) {
			_ = k.do(context.Background(), http.MethodPost, "/v1/sessions/"+s.ID+"/abort", map[string]any{}, nil)
			return Outcome{Status: "timeout"}
		}
		select {
		case <-ctx.Done():
		case <-time.After(3 * time.Second):
		}
	}
}

// Outcome of a finished run.
type Outcome struct {
	Status string // completed | failed | aborted | timeout
	Text   string
	// Error is why a failed run failed, as the engine tells people (the
	// model provider's message, such as a rate limit); ErrorClass is its
	// class (spend_limit, rate_limit, connection_reset, …) and ResetsAt when
	// a provider's spending limit lifts, if it said.
	Error, ErrorClass string
	ResetsAt          time.Time
}

// Wait polls the run until it ends or timeout passes (then aborts it).
func (k *Engine) Wait(ctx context.Context, s *Session, timeout time.Duration) Outcome {
	deadline := time.Now().Add(timeout)
	for {
		var out struct {
			Status string `json:"status"`
			Text   string `json:"text"`
			Error  string `json:"error"`
			Class  string `json:"error_class"`
			Resets string `json:"resets_at"`
		}
		err := k.do(ctx, http.MethodGet, "/v1/sessions/"+s.ID+"/runs/"+s.RunID+"/outcome", nil, &out)
		if err == nil && out.Status != "running" {
			resets, _ := time.Parse(time.RFC3339, out.Resets)
			return Outcome{Status: out.Status, Text: out.Text, Error: out.Error, ErrorClass: out.Class, ResetsAt: resets}
		}
		k.answerPending(ctx, s.ID)
		if ctx.Err() != nil || time.Now().After(deadline) {
			_ = k.do(context.Background(), http.MethodPost, "/v1/sessions/"+s.ID+"/abort", map[string]any{}, nil)
			return Outcome{Status: "timeout", Text: out.Text}
		}
		select {
		case <-ctx.Done():
		case <-time.After(5 * time.Second):
		}
	}
}

// SessionCost sums billed USD and tokens across the session's messages.
func (k *Engine) SessionCost(ctx context.Context, sessionID string) (usd float64, in, out, cached int) {
	var raw json.RawMessage
	if err := k.do(ctx, http.MethodGet, "/v1/sessions/"+sessionID+"/messages", nil, &raw); err != nil {
		return
	}
	type msg struct {
		Usage *struct {
			InputTokens          int `json:"input_tokens"`
			OutputTokens         int `json:"output_tokens"`
			CacheReadInputTokens int `json:"cache_read_input_tokens"`
			Cost                 *struct {
				BilledTotalUSD float64 `json:"billed_total_usd"`
			} `json:"cost"`
		} `json:"usage"`
	}
	var list []msg
	if json.Unmarshal(raw, &list) != nil {
		var w struct {
			Messages []msg `json:"messages"`
		}
		_ = json.Unmarshal(raw, &w)
		list = w.Messages
	}
	for _, m := range list {
		if m.Usage == nil {
			continue
		}
		in += m.Usage.InputTokens
		out += m.Usage.OutputTokens
		cached += m.Usage.CacheReadInputTokens
		if m.Usage.Cost != nil {
			usd += m.Usage.Cost.BilledTotalUSD
		}
	}
	return
}

func freePort() (int, error) {
	l, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		return 0, err
	}
	defer l.Close()
	return l.Addr().(*net.TCPAddr).Port, nil
}

// TrimForPrompt shortens text for inclusion in an opening message.
func TrimForPrompt(s string, n int) string {
	s = strings.TrimSpace(s)
	if len(s) > n {
		return s[:n] + "\n…(truncated)"
	}
	return s
}

// SessionBusy includes queued input, so an operator cannot take over a foreign
// run while it is waiting for dispatch.
func (k *Engine) SessionBusy(ctx context.Context, id string) (bool, error) {
	var status struct {
		Running bool `json:"is_running"`
		Pending int  `json:"pending_messages"`
	}
	err := k.do(ctx, http.MethodGet, "/v1/sessions/"+id+"/status", nil, &status)
	return status.Running || status.Pending > 0, err
}
