// Package runtime runs the agent engine (cmd/kodeblue-engine) as a child
// process and drives agent sessions through its HTTP API. kodeblue does not
// re-implement an agent loop: every learning run, incident and review is an
// ordinary engine session, so it gets the engine's tool loop, compaction,
// prompt caching, skills and definitions unchanged.
package runtime

